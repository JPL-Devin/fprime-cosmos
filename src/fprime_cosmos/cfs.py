"""cFS overlay: add F Prime application definitions to a pre-existing nasa/cfs-cosmos-plugin tree

F Prime applications hosted inside cFS (fprime_cfs) exchange CCSDS space packets on the cFS software bus and
reach the ground through the ordinary cFS command ingest / telemetry output applications. The cfs-cosmos-plugin
stays authoritative for cFS itself: its plugin.txt, CFS target, interfaces and protocols are copied untouched.
This module only adds, per F Prime application dictionary, one command and one telemetry definition file to the
CFS target (plus the Ruby subpacketizer those definitions use) and packages the combined tree as one gem.

Wire format (fprime_cfs CfsCmdFramer / CfsTlmFramer):
  command:   CCSDS primary header | function code (1) | checksum (1)   | F Prime command packet
  telemetry: CCSDS primary header | seconds (4)       | subseconds (2) | F Prime telemetry packet
The CCSDS items keep the cfs-cosmos-plugin names (CCSDS_STREAMID, CCSDS_LENGTH, CCSDS_CHECKSUM, ...) so its
ProtocolCcsdsChecksum and ProtocolCcsdsLength write protocols fill them unchanged. The six byte telemetry
secondary header is exactly what CfsTlmFramer emits; the generic cFS header's SPARE_FOR_64_ALIGN is not used.

COSMOS identifies a target's telemetry by one shared set of ID items as long as every packet of the target declares
the same ones; a packet with different ID items switches the whole target to per-packet matching, where the cFS
plugin's file packets (no ID items) would swallow everything defined after them. The F Prime packets therefore
identify on CCSDS_STREAMID alone, like every cFS packet: one parent packet per F Prime message id carries the F Prime
packet as a block and a subpacketizer resolves the F Prime packet or channel (SUBPACKET definitions identified by
the F Prime descriptor/packet id or channel id).
"""

from __future__ import annotations

import re
import shutil
from dataclasses import dataclass
from importlib import resources
from pathlib import Path

from fprime_cosmos import emit
from fprime_cosmos.dictionary import APID_ENUM, CFS_FUNCTION_CODE_CONSTANT, DictionaryError, FprimeDictionary
from fprime_cosmos.gem import GemSpec, build_gem
from fprime_cosmos.plugin_builder import COSMOS_MINIMUM_VERSION, PluginArtifacts, slug, version_for

CFS_TARGET = "CFS"
GEM_NAME = "openc3-cosmos-cfs"
DEFAULT_TARGET_NAME = "CFS-1"
# Stream identifier (cFS message identifier) prefixes: packet version 0, secondary header flag set, and the
# packet type bit for commands; the APID occupies the low 11 bits
COMMAND_STREAM_ID = 0x1800
TELEMETRY_STREAM_ID = 0x0800
APID_MASK = 0x07FF
COMMAND_APID = "FW_PACKET_COMMAND"
CHANNELS_APID = "FW_PACKET_TELEM"
PACKETS_APID = "FW_PACKET_PACKETIZED_TLM"
SUBPACKETIZER = "fprime_subpacketizer.rb"
STATIC_LIB = resources.files("fprime_cosmos") / "plugin_cfs"
# Ruby conversions: the CFS target is a Ruby target
TIME_CONVERSION = "openc3/conversions/unix_time_conversion.rb"
PACKET_TIME_CONVERSION = "unix_time_conversion_epoch_offset.rb"
HEADER = "# Generated by fprime-to-cosmos-cfs from {dictionary} ({deployment}). Do not edit.\n"
# Plugin pieces staged by the cfs-cosmos-plugin Makefile / listed by its gemspec
PLUGIN_DIRECTORIES = ("targets", "lib", "tools", "microservices")
PLUGIN_FILES = ("Rakefile", "README.md", "LICENSE.txt", "plugin.txt", "requirements.txt")
PACKETIZED_PACKET = "FPRIME_PACKETS"
PACKET_BLOCK = "PACKET"
CFS_MESSAGE_LIST = Path("targets") / CFS_TARGET / "lib" / "cfs_cmd_tlm_list.rb"
CFS_GLOBALS = Path("targets") / CFS_TARGET / "lib" / "cfs_globals.rb"
CFS_STREAM_ID = re.compile(r"base_stream_id:\s*0[xX]([0-9A-Fa-f]+)")
CFS_TOTAL_CPUS = re.compile(r"\$cfs_total_valid_cpus\s*=\s*(\d+)")
# The cFS plugin derives a target's message ids from the base ids in its message list by writing the cpu number
# (target CFS-<n> is cpu n-1) into the three bit field above the low byte (cfs_cmd_tlm_list.rb)
CFS_CPU_FIELD_MASK = 0xF8FF
CFS_CPU_FIELD_SHIFT = 8
DEFAULT_CFS_CPUS = 2


class CfsOverlayError(Exception):
    """The plugin tree or the set of dictionaries cannot be combined"""


@dataclass(frozen=True)
class CfsApp:
    """One F Prime application hosted in cFS: its dictionary and the identifiers derived from ComCfg"""

    dictionary: FprimeDictionary
    name: str
    command_mid: int
    channels_mid: int
    packets_mid: int
    function_code: int

    @property
    def slug(self) -> str:
        return slug(self.name)

    def packet_name(self, name: str) -> str:
        return f"{self.name}.{name}"

    def message_ids(self, channelized: bool = True) -> dict[str, int]:
        ids = {"command": self.command_mid, "packetized telemetry": self.packets_mid}
        if channelized:
            ids["channelized telemetry"] = self.channels_mid
        return ids


def _stream_id(prefix: int, apids: dict[str, int], key: str, dictionary: FprimeDictionary) -> int:
    apid = apids[key]
    if not 0 <= apid <= APID_MASK:
        raise DictionaryError(f"{dictionary.path.name}: {APID_ENUM}.{key} = {apid:#x} is not an 11 bit APID")
    return prefix | apid


def cfs_app(dictionary: FprimeDictionary) -> CfsApp:
    """Derive the cFS identifiers of an F Prime application from its dictionary, or raise DictionaryError"""
    name = dictionary.path.name
    apids = dictionary.apids
    if not apids:
        raise DictionaryError(f"{name}: no {APID_ENUM} enumeration; cFS hosted F Prime dictionaries define it")
    missing = [key for key in (COMMAND_APID, CHANNELS_APID, PACKETS_APID) if key not in apids]
    if missing:
        raise DictionaryError(f"{name}: {APID_ENUM} lacks {', '.join(missing)}")
    if dictionary.cfs_function_code is None:
        raise DictionaryError(f"{name}: missing dictionary constant {CFS_FUNCTION_CODE_CONSTANT}")
    if not 0 <= dictionary.cfs_function_code <= 0x7F:
        raise DictionaryError(f"{name}: {CFS_FUNCTION_CODE_CONSTANT} = {dictionary.cfs_function_code} exceeds 7 bits")
    return CfsApp(
        dictionary=dictionary,
        name=emit.identifier(dictionary.deployment_name.rsplit(".", 1)[-1]),
        command_mid=_stream_id(COMMAND_STREAM_ID, apids, COMMAND_APID, dictionary),
        channels_mid=_stream_id(TELEMETRY_STREAM_ID, apids, CHANNELS_APID, dictionary),
        packets_mid=_stream_id(TELEMETRY_STREAM_ID, apids, PACKETS_APID, dictionary),
        function_code=dictionary.cfs_function_code,
    )


def cfs_plugin_cpus(plugin: Path) -> int:
    """Number of cFS cpus (CFS-<n> targets) the plugin instantiates"""
    path = Path(plugin) / CFS_GLOBALS
    match = CFS_TOTAL_CPUS.search(path.read_text()) if path.is_file() else None
    return int(match.group(1)) if match else DEFAULT_CFS_CPUS


def cfs_plugin_message_ids(plugin: Path) -> dict[int, str]:
    """Message ids the cFS plugin already defines for its CFS-<n> targets, by message list source line"""
    path = Path(plugin) / CFS_MESSAGE_LIST
    if not path.is_file():
        return {}
    found = {}
    for number, line in enumerate(path.read_text().splitlines(), start=1):
        match = CFS_STREAM_ID.search(line)
        if match:
            base = int(match.group(1), 16)
            for cpu in range(cfs_plugin_cpus(plugin)):
                mid = (base & CFS_CPU_FIELD_MASK) | (cpu << CFS_CPU_FIELD_SHIFT)
                found.setdefault(mid, f"{CFS_MESSAGE_LIST.as_posix()}:{number} (CFS-{cpu + 1})")
    return found


def check_collisions(apps: list[CfsApp], plugin: Path, channelized: bool = True) -> None:
    """Raise CfsOverlayError when application names or message identifiers collide, with each other or with cFS"""
    owners: dict[int, str] = {}
    names: dict[str, str] = {}
    for app in apps:
        source = app.dictionary.path.name
        if app.name in names:
            raise CfsOverlayError(f"Application name {app.name} is used by both {names[app.name]} and {source}")
        names[app.name] = source
        for kind, mid in app.message_ids(channelized).items():
            owner = f"{source} {kind}"
            if mid in owners:
                raise CfsOverlayError(f"Message id {mid:#06x} collides: {owners[mid]} and {owner}")
            owners[mid] = owner
    cfs_ids = cfs_plugin_message_ids(plugin)
    for mid, owner in owners.items():
        if mid in cfs_ids:
            raise CfsOverlayError(
                f"Message id {mid:#06x} ({owner}) is already defined by the cFS plugin at {cfs_ids[mid]}"
            )


def header(dictionary: FprimeDictionary) -> str:
    return HEADER.format(dictionary=emit.quote(dictionary.path.name), deployment=emit.quote(dictionary.deployment_name))


def _command_header(app: CfsApp) -> list[str]:
    """The cfs-cosmos-plugin command header items (cfs_cmd_hdr) with the F Prime two byte secondary header"""
    streamid = f"CCSDS_STREAMID 16 UINT MIN_UINT16 MAX_UINT16 {app.command_mid:#06x}"
    sequence = "CCSDS_SEQUENCE 16 UINT MIN_UINT16 MAX_UINT16 0xC000"
    return [
        f'  APPEND_ID_PARAMETER {streamid} "CCSDS Packet Identification" BIG_ENDIAN',
        '    FORMAT_STRING "0x%04X"',
        f'  APPEND_PARAMETER {sequence} "CCSDS Packet Sequence Control" BIG_ENDIAN',
        '  APPEND_PARAMETER CCSDS_LENGTH 16 UINT MIN_UINT16 MAX_UINT16 1 "CCSDS Packet Data Length" BIG_ENDIAN',
        f'  APPEND_PARAMETER CCSDS_FC 8 UINT MIN_UINT8 MAX_UINT8 {app.function_code} "CCSDS Command Function Code"',
        '  APPEND_PARAMETER CCSDS_CHECKSUM 8 UINT MIN_UINT8 MAX_UINT8 0 "CCSDS Command Checksum"',
    ]


def _telemetry_header(mid: int) -> list[str]:
    """The cfs-cosmos-plugin telemetry header items (cfs_tlm_hdr) with the six byte secondary header only"""
    return [
        f'  APPEND_ID_ITEM CCSDS_STREAMID 16 UINT {mid:#06x} "CCSDS Packet Identification" BIG_ENDIAN',
        '    FORMAT_STRING "0x%04X"',
        '  APPEND_ITEM CCSDS_SEQUENCE 16 UINT "CCSDS Packet Sequence Control" BIG_ENDIAN',
        '  APPEND_ITEM CCSDS_LENGTH 16 UINT "CCSDS Packet Data Length" BIG_ENDIAN',
        '  APPEND_ITEM SECONDS 32 UINT "CCSDS Telemetry Secondary Header (seconds)" BIG_ENDIAN',
        '  APPEND_ITEM SUBSECS 16 UINT "CCSDS Telemetry Secondary Header (subseconds)" BIG_ENDIAN',
        '  ITEM PACKET_TIME 0 0 DERIVED "Ruby time based on SECONDS and SUBSECS"',
        f"    READ_CONVERSION {PACKET_TIME_CONVERSION} SECONDS SUBSECS",
    ]


def emit_command(command, app: CfsApp) -> list[str]:
    name = app.packet_name(emit.full_name(command))
    lines = [f"COMMAND {emit.TARGET} {name} BIG_ENDIAN {emit.quote(command.get_description())}"]
    lines.extend(_command_header(app))
    lines.extend(emit.emit_command(command, app.dictionary.layout)[1:])
    return lines


def emit_commands(app: CfsApp) -> str:
    blocks = [header(app.dictionary)]
    for command in app.dictionary.commands:
        blocks.append("\n".join(emit_command(command, app)) + "\n")
    return "\n".join(blocks)


def _parent(app: CfsApp, name: str, mid: int, description: str, block: str, block_description: str) -> list[str]:
    """A parent packet: identified by the cFS message id, carrying the F Prime packet for the subpacketizer"""
    lines = [f"TELEMETRY {emit.TARGET} {app.packet_name(name)} BIG_ENDIAN {emit.quote(description)}"]
    lines.append(f"  SUBPACKETIZER {SUBPACKETIZER}")
    lines.extend(_telemetry_header(mid))
    lines.append(f"  APPEND_ITEM {block} 0 BLOCK {emit.quote(block_description)}")
    lines.append("    HIDDEN")
    return lines


def emit_channelized_parent(app: CfsApp) -> list[str]:
    description = "F Prime channelized telemetry (split into one subpacket per channel)"
    block = "F Prime packet descriptor and concatenated channel records"
    return _parent(app, emit.CHANNELIZED_PACKET, app.channels_mid, description, emit.CHANNELS_BLOCK, block)


def emit_packetized_parent(app: CfsApp) -> list[str]:
    description = "F Prime packetized telemetry (resolved to one subpacket per F Prime packet)"
    return _parent(app, PACKETIZED_PACKET, app.packets_mid, description, PACKET_BLOCK, "F Prime telemetry packet")


def emit_channel(channel, app: CfsApp) -> list[str]:
    """A channel subpacket: the native definition under the application-prefixed name"""
    name = app.packet_name(emit.full_name(channel))
    lines = [f"TELEMETRY {emit.TARGET} {name} BIG_ENDIAN {emit.quote(channel.get_ch_desc())}"]
    lines.extend(emit.emit_channel(channel, app.dictionary.layout, TIME_CONVERSION)[1:])
    return lines


def emit_packet(packet, app: CfsApp) -> list[str]:
    """A packetized telemetry subpacket: the native definition (descriptor and packet id as ID items)"""
    name = app.packet_name(emit.full_name(packet))
    description = emit.quote(f"F Prime packetized telemetry {packet.get_name()}")
    lines = [f"TELEMETRY {emit.TARGET} {name} BIG_ENDIAN {description}", "  SUBPACKET"]
    lines.extend(emit.emit_packet(packet, app.dictionary.layout, TIME_CONVERSION)[1:])
    return lines


def emit_telemetry(app: CfsApp, channelized: bool = True) -> str:
    """The packetized parent and its packets and, unless channelized is false, the channelized parent and channels

    No catch-all packet is generated: unidentified cFS packets stay the cFS plugin's business.
    """
    blocks = [header(app.dictionary)]
    blocks.append("\n".join(emit_packetized_parent(app)) + "\n")
    for packet in app.dictionary.packets:
        blocks.append("\n".join(emit_packet(packet, app)) + "\n")
    if channelized:
        blocks.append("\n".join(emit_channelized_parent(app)) + "\n")
        for channel in app.dictionary.channels:
            blocks.append("\n".join(emit_channel(channel, app)) + "\n")
    return "\n".join(blocks)


def definition_files(app: CfsApp) -> tuple[str, str]:
    """Command and telemetry definition file names, following the cFS plugin's *_cmd_def.txt / *_tlm_def.txt"""
    return f"fprime_{app.slug}_cmd_def.txt", f"fprime_{app.slug}_tlm_def.txt"


def validate_plugin(plugin: Path) -> Path:
    plugin = Path(plugin)
    if not (plugin / "plugin.txt").is_file():
        raise CfsOverlayError(f"{plugin} is not a COSMOS plugin tree (no plugin.txt)")
    if not (plugin / "targets" / CFS_TARGET / "cmd_tlm").is_dir():
        raise CfsOverlayError(f"{plugin} has no targets/{CFS_TARGET}/cmd_tlm directory; expected a cfs-cosmos-plugin")
    return plugin


def stage_plugin(plugin: Path, destination: Path) -> None:
    """Copy the plugin pieces its own Makefile stages (and its gemspec packages) into destination, untouched"""
    destination.mkdir(parents=True)
    for name in PLUGIN_DIRECTORIES:
        if (plugin / name).is_dir():
            shutil.copytree(plugin / name, destination / name, ignore=shutil.ignore_patterns("__pycache__"))
    for path in sorted(plugin.glob("*.gemspec")):
        shutil.copy2(path, destination / path.name)
    for name in PLUGIN_FILES:
        if (plugin / name).is_file():
            shutil.copy2(plugin / name, destination / name)


def write_overlay(plugin: Path, apps: list[CfsApp], output: Path, channelized: bool = True) -> Path:
    """Stage the cFS plugin under output and add the F Prime definitions; returns the plugin directory"""
    plugin = validate_plugin(plugin)
    check_collisions(apps, plugin, channelized)
    output = Path(output)
    if output.exists():
        shutil.rmtree(output)
    stage_plugin(plugin, output)
    target = output / "targets" / CFS_TARGET
    with resources.as_file(STATIC_LIB / SUBPACKETIZER) as subpacketizer:
        shutil.copy2(subpacketizer, target / "lib" / SUBPACKETIZER)
    for app in apps:
        commands, telemetry = definition_files(app)
        (target / "cmd_tlm" / commands).write_text(emit_commands(app))
        (target / "cmd_tlm" / telemetry).write_text(emit_telemetry(app, channelized))
    return output


def build_overlay(
    plugin: Path, dictionaries: list[FprimeDictionary], output: Path, channelized: bool = True, gem: bool = True
) -> PluginArtifacts:
    """Write the combined plugin to output/<gem name> and, optionally, build output/<gem name>-<version>.gem"""
    if not dictionaries:
        raise CfsOverlayError("At least one F Prime dictionary is required")
    apps = [cfs_app(dictionary) for dictionary in dictionaries]
    output = Path(output)
    directory = write_overlay(plugin, apps, output / GEM_NAME, channelized)
    version = version_for(directory)
    gem_path = None
    if gem:
        hashes = ", ".join(f"{app.dictionary.path.name} ({app.dictionary.content_hash()})" for app in apps)
        names = ", ".join(app.name for app in apps)
        spec = GemSpec(
            name=GEM_NAME,
            version=version,
            summary=f"OpenC3 COSMOS plugin for cFS with the F Prime applications {names}",
            description=f"cfs-cosmos-plugin {Path(plugin).resolve()} plus fprime-to-cosmos-cfs output for {hashes}",
            metadata={
                "openc3_cosmos_minimum_version": COSMOS_MINIMUM_VERSION,
                "fprime_dictionary_hash": ",".join(app.dictionary.content_hash() for app in apps),
            },
        )
        gem_path = build_gem(spec, directory, output / f"{GEM_NAME}-{version}.gem")
    return PluginArtifacts(directory=directory, gem_name=GEM_NAME, version=version, gem_path=gem_path)
